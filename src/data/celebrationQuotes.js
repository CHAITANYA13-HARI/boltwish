export function getQuotesByOccasion(occasion) {
  if (!occasion || occasion === 'all') return celebrationQuotes;
  const normalized = String(occasion).toLowerCase();
  const matched = celebrationQuotes.filter((q) => q.category === normalized);
  return matched.length ? matched : celebrationQuotes;
}
